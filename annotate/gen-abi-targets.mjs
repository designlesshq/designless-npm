#!/usr/bin/env node
/**
 * Generate the older-ABI SWC plugin crate(s).
 *
 * An SWC wasm plugin is compiled against ONE `swc_core` and can only be loaded
 * by a host whose `swc_plugin_runner` speaks the same plugin AST schema. There
 * is no runtime negotiation. A mismatch is not a skipped transform - it is
 * `failed to invoke plugin`, which Next reports as a build error and serves as
 * a 500.
 *
 * MEASURED compatibility (each wasm loaded through the host's own @next/swc
 * binary, 2026-08-29) - not inferred from version numbers, which is how this
 * was got wrong the first time:
 *
 *     host                          core35   core68
 *     Next 15.5.19 (runner 18)      ok       REJECTED
 *     Next 16.1.7  (runner 23)      REJECTED ok
 *     Next 16.2.1  (runner 24)      REJECTED ok
 *
 * So the generations are WIDE: runners 23, 24 and 29 all accept the same
 * artifact, and the only boundary we have actually observed sits between
 * Next 15 and Next 16. Two artifacts cover every Next in the wild today.
 *
 * Do NOT key this on the Next version. Next 16.1 and 16.2 embed different
 * runners; a "next15/next16" split is wrong by construction even though the
 * current boundary happens to fall there. The crates are named for the
 * `swc_core` they pin, which is the only thing that is actually true of them.
 *
 * To add a target: build it, then add it to CANDIDATES in src/next.js. The
 * wrapper preflights candidates against the real host binary, so a wrong guess
 * costs a skipped marker, never a broken dev server.
 */
import { writeFileSync, mkdirSync } from 'node:fs'

export const TARGETS = [
  {
    core: '35',
    // Does this swc_core have JSXAttrValue::Str? Older cores wrap it as
    // ::Lit(Lit::Str). Verified by compiling; it is not guessable.
    jsxAttrStr: false,
    hosts: 'Next 15.5.x (swc_plugin_runner 18)',
    // swc_core 35 asks for `swc_plugin_macro ^1.1.0`, and 1.1.1 REMOVED
    // `css_plugin_transform`, a symbol swc_core 35 still re-exports. A caret
    // range therefore resolves to a version that cannot compile the crate that
    // asked for it, and the error lands inside swc_core with no mention of us.
    pins: { swc_plugin_macro: '=1.1.0' },
  },
]

export function generate() {
  for (const t of TARGETS) {
    const dir = `swc-plugin-core${t.core}`
    mkdirSync(dir, { recursive: true })
    const pins = Object.entries(t.pins).map(([k, v]) => `${k} = "${v}"`).join('\n')
    writeFileSync(`${dir}/Cargo.toml`, `# GENERATED by gen-abi-targets.mjs - do not hand-edit.
#
# ABI target: swc_core ${t.core}. Known hosts: ${t.hosts}.
#
# The SOURCE is shared with ../swc-plugin - one lib.rs, one behaviour, two ABI
# pins. The only construct the cores disagree on is a single JSX attribute
# value, behind the \`swc_jsx_attr_str\` cfg that build.rs sets per target.
[package]
name = "designless-annotate-swc-core${t.core}"
version = "0.1.0"
edition = "2021"
license = "Apache-2.0"
description = "SWC plugin (swc_core ${t.core} ABI): stamp annotate/v1 source markers on host JSX elements."
publish = false
build = "build.rs"

[lib]
crate-type = ["cdylib"]
path = "../swc-plugin/src/lib.rs"

[dependencies]
swc_core = { version = "${t.core}", features = ["ecma_plugin_transform", "ecma_ast", "ecma_visit", "common"] }
${pins ? pins + '\n' : ''}serde = { version = "1", features = ["derive"] }
serde_json = "1"

[profile.release]
opt-level = "z"
lto = true
strip = true
`)
    writeFileSync(`${dir}/build.rs`, `// GENERATED by gen-abi-targets.mjs - do not hand-edit.
fn main() {
    println!("cargo::rustc-check-cfg=cfg(swc_jsx_attr_str)");
${t.jsxAttrStr ? '    println!("cargo::rustc-cfg=swc_jsx_attr_str");\n' : ''}}
`)
    console.log(`generated ${dir} (swc_core ${t.core}, jsxAttrStr=${t.jsxAttrStr})`)
  }
}

// Only generate when run directly; importing this for TARGETS must be pure.
if (process.argv[1] && process.argv[1].endsWith('gen-abi-targets.mjs')) generate()
